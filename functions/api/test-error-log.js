// ============================================================================
// Pages Function: /api/test-error-log
// ============================================================================
// PURPOSE: Test endpoint that intentionally triggers a system error and
//   writes it to the error_log D1 table. Used to verify the Error Logs tab
//   in the Owner Dashboard is working end-to-end.
//
// USAGE: Visit https://www.driv-en.com/api/test-error-log in your browser.
//   It will:
//     1. Auto-create the error_log table (if it doesn't exist)
//     2. Insert a test error with source, message, stack trace, and timestamp
//     3. Return a JSON confirmation
//
// After visiting, open the Owner Dashboard → Error Logs tab to see the entry.
//
// SAFE TO DELETE: This file can be removed once error logging is verified.
// ============================================================================

export async function onRequest(context) {
  const { env } = context;

  const headers = {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*'
  };

  try {
    // 1. Ensure the error_log table exists
    await env.DB.prepare(
      `CREATE TABLE IF NOT EXISTS error_log (
        id TEXT PRIMARY KEY,
        source TEXT,
        error_message TEXT,
        stack_trace TEXT,
        severity TEXT DEFAULT 'error',
        resolved INTEGER DEFAULT 0,
        created_at TEXT
      )`
    ).run();

    // 2. Generate a test error entry
    const errorId = 'TEST-' + Date.now() + '-' + Math.random().toString(36).substr(2, 9);
    const testError = new Error('Test error: This is a simulated system failure to verify the Error Log pipeline is working.');
    testError.stack = testError.stack + '\n\n--- TEST CONTEXT ---\nThis is an intentional test error generated by /api/test-error-log\nTime: ' + new Date().toISOString();

    // 3. Insert into error_log
    await env.DB.prepare(
      `INSERT INTO error_log (id, source, error_message, stack_trace, severity, resolved, created_at)
       VALUES (?, ?, ?, ?, 'error', 0, ?)`
    ).bind(
      errorId,
      'test-error-log (intentional test)',
      testError.message,
      testError.stack,
      new Date().toISOString()
    ).run();

    // 4. Return confirmation
    return new Response(JSON.stringify({
      success: true,
      message: 'Test error logged successfully.',
      errorId: errorId,
      instructions: 'Open the Owner Dashboard → Error Logs tab to see this entry.',
      note: 'You can safely delete /functions/api/test-error-log.js after verifying.'
    }, null, 2), { status: 200, headers });

  } catch (err) {
    return new Response(JSON.stringify({
      success: false,
      error: 'Failed to log test error: ' + err.message,
      stack: err.stack
    }, null, 2), { status: 500, headers });
  }
}
